/**
 * Workspace Initialization and Repair
 * 
 * Handles setting up fedmgr workspaces with proper directory structure,
 * configuration files, and environment detection.
 */

const fs = require('fs');
const path = require('path');
const os = require('os');

/**
 * Detect the current environment and suggest appropriate configuration
 */
function detectEnvironment(workspacePath) {
  const environment = {
    type: 'development', // default
    isDocker: false,
    isNpmGlobal: false,
    isGitRepo: false,
    hasPackageJson: false,
    platform: os.platform(),
    nodeVersion: process.version
  };

  // Check if running in Docker
  if (fs.existsSync('/.dockerenv') || process.env.DOCKER_CONTAINER) {
    environment.isDocker = true;
    environment.type = 'docker';
  }

  // Check if this is an npm global installation
  if (__dirname.includes('node_modules') && __dirname.includes('global')) {
    environment.isNpmGlobal = true;
    environment.type = 'global';
  }

  // Check if workspace is a git repository
  if (fs.existsSync(path.join(workspacePath, '.git'))) {
    environment.isGitRepo = true;
  }

  // Check if workspace has package.json
  if (fs.existsSync(path.join(workspacePath, 'package.json'))) {
    environment.hasPackageJson = true;
  }

  return environment;
}

/**
 * Generate environment-appropriate configuration
 */
function generateConfiguration(workspacePath, environment) {
  const config = {
    FEDMGR_HOME: workspacePath,
    FEDMGR_BUILD_DIR: path.join(workspacePath, 'build'),
    FEDMGR_BUILD_DIR_REL: 'build',
    FEDMGR_BUILD_REL_NPM_DIR: 'build/npm',
    FEDMGR_BUILD_NPM_DIR: path.join(workspacePath, 'build/npm'),
    FEDMGR_INSTALL_DIR_REL: 'install',
    FEDMGR_INSTALL_DIR: 'build/install',
    FEDMGR_FEDERATIONS_DIR: path.join(workspacePath, 'build/install/federations'),
    FEDMGR_FED_REG: path.join(workspacePath, 'build/install/fed-reg'),
    FEDMGR_FED_REG_DIR: path.join(workspacePath, 'build/install/fed-reg'),
    FEDMGR_FED_REG_FILE: path.join(workspacePath, 'build/install/fed-reg/registry.json'),
    FEDMGR_DEF_FED: 'alpha',
    
    // OIDC Provider settings
    OIDC_PROVIDER_HOST: 'localhost',
    OIDC_PROVIDER_PORT: '6432',
    OIDC_PROVIDER_INTERNAL_PORT: '3000',
    OIDC_PROVIDER_URL: 'http://localhost:6432',
    OIDC_CLIENT_ID: 'fedmgr-cli',
    OIDC_CLIENT_SECRET: 'fedmgr-cli-secret',
    
    // MCP Core settings
    MCP_PORT: '3000',
    MCP_HOST: '0.0.0.0',
    MCP_ID: 'mcp-demo-server',
    MCP_PUBLIC_KEY: 'mcp-demo-public-key',
    MCP_BASE_URL: 'http://localhost:3000',
    
    // Trust and storage paths
    TRUST_STORE_PATH: path.join(workspacePath, 'data/trust-store.json'),
    STATS_STORAGE_PATH: path.join(workspacePath, 'data/stats.json'),
    
    // Development settings
    NODE_ENV: 'development'
  };

  // Environment-specific adjustments
  if (environment.isDocker) {
    config.MCP_HOST = '0.0.0.0';
    config.FEDMGR_PUBLIC_DIR = '/usr/src/app/public';
    config.MCP_PUBLIC_DIR = '/usr/src/app/public-mcp';
    config.FEDERATION_ADMIN_URL = 'http://federation-admin:3001';
  } else {
    config.FEDMGR_PUBLIC_DIR = path.join(workspacePath, 'public');
    config.MCP_PUBLIC_DIR = path.join(workspacePath, 'public-mcp');
    config.FEDERATION_ADMIN_URL = 'http://localhost:3001';
  }

  return config;
}

/**
 * Create directory structure
 */
function createDirectoryStructure(workspacePath) {
  const directories = [
    'build',
    'build/install',
    'build/install/federations',
    'build/install/fed-reg',
    'build/npm',
    'data',
    'public',
    'public-mcp',
    'logs'
  ];

  const created = [];

  directories.forEach(dir => {
    const fullPath = path.join(workspacePath, dir);
    if (!fs.existsSync(fullPath)) {
      fs.mkdirSync(fullPath, { recursive: true });
      created.push(fullPath);
    }
  });

  return created;
}

/**
 * Generate .env file
 */
function generateEnvFile(workspacePath, config, force = false) {
  const envPath = path.join(workspacePath, '.env');
  
  if (fs.existsSync(envPath) && !force) {
    return { created: false, path: envPath, reason: 'File already exists' };
  }

  const envContent = Object.entries(config)
    .map(([key, value]) => `${key}=${value}`)
    .join('\n');

  const header = `# fedmgr Configuration
# Generated by fedmgr init on ${new Date().toISOString()}
# Workspace: ${workspacePath}

`;

  fs.writeFileSync(envPath, header + envContent + '\n');
  
  return { created: true, path: envPath };
}

/**
 * Create initial registry file
 */
function createRegistryFile(registryPath) {
  const registryDir = path.dirname(registryPath);
  
  if (!fs.existsSync(registryDir)) {
    fs.mkdirSync(registryDir, { recursive: true });
  }

  const initialRegistry = {
    version: '1.0.0',
    created: new Date().toISOString(),
    federations: [],
    mcps: {},
    mcpProtocolServers: {},
    entityStatements: {}
  };

  fs.writeFileSync(registryPath, JSON.stringify(initialRegistry, null, 2));
  
  return registryPath;
}

/**
 * Create sample files
 */
function createSampleFiles(workspacePath) {
  const created = [];

  // Create a simple README
  const readmePath = path.join(workspacePath, 'README-fedmgr.md');
  if (!fs.existsSync(readmePath)) {
    const readmeContent = `# fedmgr Workspace

This directory has been initialized as a fedmgr workspace.

## Quick Start

1. Create a federation:
   \`\`\`bash
   fedmgr create fed my-federation
   \`\`\`

2. List your resources:
   \`\`\`bash
   fedmgr list
   \`\`\`

3. Create an MCP server:
   \`\`\`bash
   fedmgr create mcp my-mcp --federation my-federation
   \`\`\`

## Directory Structure

- \`build/install/federations/\` - Federation configurations and keys
- \`build/install/fed-reg/\` - Registry database
- \`data/\` - Runtime data and logs
- \`public/\` - Static web assets

## Configuration

Configuration is managed through the \`.env\` file in this directory.
`;

    fs.writeFileSync(readmePath, readmeContent);
    created.push(readmePath);
  }

  // Create .gitignore if this is a git repo
  const gitignorePath = path.join(workspacePath, '.gitignore');
  if (fs.existsSync(path.join(workspacePath, '.git')) && !fs.existsSync(gitignorePath)) {
    const gitignoreContent = `# fedmgr workspace
.env
build/install/federations/*/keys/*.pem
data/
logs/
*.log
node_modules/
.DS_Store
`;

    fs.writeFileSync(gitignorePath, gitignoreContent);
    created.push(gitignorePath);
  }

  return created;
}

/**
 * Initialize a new workspace
 */
async function initializeWorkspace(workspacePath, options = {}) {
  try {
    console.log(`🔍 Analyzing workspace: ${workspacePath}`);
    
    const environment = detectEnvironment(workspacePath);
    console.log(`📊 Environment detected: ${environment.type} (${environment.platform})`);
    
    const config = generateConfiguration(workspacePath, environment);
    
    // Check if workspace already exists
    const envPath = path.join(workspacePath, '.env');
    if (fs.existsSync(envPath) && !options.force) {
      return {
        success: false,
        error: 'Workspace already initialized. Use --force to overwrite or --fix to repair.'
      };
    }

    const created = [];

    // Create directory structure
    console.log('📁 Creating directory structure...');
    const createdDirs = createDirectoryStructure(workspacePath);
    created.push(...createdDirs.map(dir => `Directory: ${path.relative(workspacePath, dir)}`));

    // Generate .env file
    console.log('⚙️  Generating configuration...');
    const envResult = generateEnvFile(workspacePath, config, options.force);
    if (envResult.created) {
      created.push(`Configuration: .env`);
    }

    // Create registry file
    console.log('📋 Creating registry...');
    const registryPath = createRegistryFile(config.FEDMGR_FED_REG_FILE);
    created.push(`Registry: ${path.relative(workspacePath, registryPath)}`);

    // Create sample files
    console.log('📄 Creating sample files...');
    const sampleFiles = createSampleFiles(workspacePath);
    created.push(...sampleFiles.map(file => `Sample: ${path.relative(workspacePath, file)}`));

    return {
      success: true,
      created,
      environment,
      config
    };

  } catch (error) {
    return {
      success: false,
      error: error.message
    };
  }
}

/**
 * Repair an existing workspace
 */
async function repairWorkspace(workspacePath, options = {}) {
  try {
    console.log(`🔍 Analyzing existing workspace: ${workspacePath}`);
    
    const environment = detectEnvironment(workspacePath);
    const config = generateConfiguration(workspacePath, environment);
    const changes = [];

    // Check and fix directory structure
    console.log('📁 Checking directory structure...');
    const createdDirs = createDirectoryStructure(workspacePath);
    if (createdDirs.length > 0) {
      changes.push(`Created ${createdDirs.length} missing directories`);
    }

    // Check registry file
    console.log('�� Checking registry...');
    const registryPath = config.FEDMGR_FED_REG_FILE;
    
    // Fix common issue: registry path pointing to directory
    if (fs.existsSync(config.FEDMGR_FED_REG_DIR)) {
      const stat = fs.statSync(config.FEDMGR_FED_REG_DIR);
      if (stat.isDirectory() && !fs.existsSync(registryPath)) {
        createRegistryFile(registryPath);
        changes.push('Created missing registry.json file');
      }
    } else {
      createRegistryFile(registryPath);
      changes.push('Created registry file and directory');
    }

    // Check .env file
    console.log('⚙️  Checking configuration...');
    const envPath = path.join(workspacePath, '.env');
    if (!fs.existsSync(envPath) || options.force) {
      const envResult = generateEnvFile(workspacePath, config, true);
      if (envResult.created) {
        changes.push('Updated .env configuration');
      }
    } else {
      // Validate existing .env
      const existingEnv = fs.readFileSync(envPath, 'utf-8');
      const missingVars = [];
      
      Object.keys(config).forEach(key => {
        if (!existingEnv.includes(`${key}=`)) {
          missingVars.push(key);
        }
      });
      
      if (missingVars.length > 0) {
        changes.push(`Found ${missingVars.length} missing environment variables (consider updating .env)`);
      }
    }

    // Validate paths in .env point to correct locations
    console.log('🔍 Validating configuration paths...');
    const pathIssues = [];
    
    // Check if FEDMGR_FED_REG_FILE points to a directory (common issue)
    const currentEnv = process.env;
    if (currentEnv.FEDMGR_FED_REG_FILE) {
      if (fs.existsSync(currentEnv.FEDMGR_FED_REG_FILE)) {
        const stat = fs.statSync(currentEnv.FEDMGR_FED_REG_FILE);
        if (stat.isDirectory()) {
          pathIssues.push('FEDMGR_FED_REG_FILE points to directory instead of file');
        }
      }
    }
    
    if (pathIssues.length > 0) {
      changes.push(`Fixed ${pathIssues.length} path configuration issues`);
    }

    return {
      success: true,
      changes,
      environment,
      pathIssues
    };

  } catch (error) {
    return {
      success: false,
      error: error.message
    };
  }
}

module.exports = {
  initializeWorkspace,
  repairWorkspace,
  detectEnvironment,
  generateConfiguration
};
